let frutas = ["Uva", "Morango", "Laranja"]

/* método push adiciona item no final da lista */
frutas.push("Banana")
console.log(frutas)

/* Remove o ultimo item da lista */
frutas.pop()
console.log(frutas)

/* Remove o primeiro item da lista */
frutas.shift()
console.log(frutas)

/* Adicione no inicio da lista */
frutas.unshift("Abacate")
console.log(frutas)

/* Mostra a quantidade de elementos na lista */
console.log(frutas.length)

/* Verifica se um valor existe na lista */
console.log(frutas.includes("Abacate"))














































